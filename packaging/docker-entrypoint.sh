#!/usr/bin/env bash
#
# Boots (and on first boot, provisions) the Social Spot server inside its container.
#
# Invoked as the image ENTRYPOINT. With no arguments (or `app`) it provisions and then
# starts Apache; with `worker` it provisions and then runs the background-job daemon in
# the foreground (`bin/console.php daemon start -f` - the non-deprecated worker entry
# point since core 2026.01).
#
# Design rules, all learned from tools/dev/instance.sh:
#   * every start is safe to repeat - restarts and image upgrades re-run this script;
#   * environment variables own infrastructure (database connection, base URL, admin
#     identity); the officer console owns organization life (profile fine-tuning,
#     features, theme). The script seeds the second group exactly once, on first
#     boot, and never touches it again, so it cannot clobber an officer's choices;
#   * per-instance organization defaults travel through config/orgsuite.config.php,
#     which OrgConfig reads as a FALLBACK behind stored values - regenerating it on
#     every boot is safe, and it is how the profile takes effect before anyone logs in;
#   * the admin password is set only when the account is created. Resetting it on
#     every boot would lock out whoever changed it in the console afterwards.
#
set -euo pipefail

CORE=/var/www/friendica

DB_HOST="${DB_HOST:-db}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:?the database name (DB_NAME) is not set}"
DB_USER="${DB_USER:?the database user (DB_USER) is not set}"
DB_PASSWORD="${DB_PASSWORD:?the database password (DB_PASSWORD) is not set}"

BASE_URL="${BASE_URL:?the public address (BASE_URL) is not set, e.g. https://social.example.org}"
ORG_NAME="${ORG_NAME:-Social Spot}"
ORG_PROFILE="${ORG_PROFILE:-hoa}"

ADMIN_NICK="${ADMIN_NICK:-admin}"
ADMIN_PASS="${ADMIN_PASS:?no administrator password (ADMIN_PASS) is set}"
ADMIN_MAIL="${ADMIN_MAIL:-admin@example.com}"

log() { printf '[entrypoint] %s\n' "$*"; }
die() { printf '[entrypoint] %s\n' "$*" >&2; exit 1; }

# Escape a value for single-quoted PHP.
esc() { printf '%s' "$1" | sed "s/'/\\\\'/g"; }

# Everything that touches the application runs as www-data: Apache serves as that
# user, and console commands run as root would leave root-owned files (compiled
# templates, caches) that the server then cannot write to.
console() {
  ( cd "$CORE" && gosu www-data php bin/console.php "$@" )
}

sql() {
  mariadb -h"$DB_HOST" -P"$DB_PORT" -u"$DB_USER" -p"$DB_PASSWORD" -N -B "$DB_NAME" -e "$1"
}

# The config table only exists after a successful installation, so its absence
# reliably means "first boot" and lets upgrades re-run this script harmlessly.
is_installed() {
  [[ "$(sql "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='$DB_NAME' AND table_name='config';" 2>/dev/null || echo 0)" == "1" ]]
}

write_local_config() {
  local with_policy="$1"

  {
    printf '<?php\n\n/**\n * Generated by docker-entrypoint.sh from the container environment - do not edit.\n *\n * Infrastructure truth (database, base URL, admin identity) is regenerated on every\n * boot from the environment. Organization life (features, theme, wording) lives in\n * the database once an officer touches it and is only seeded on first boot.\n */\n\nreturn [\n'
    printf "\t'database' => [\n\t\t'hostname' => '%s:%s',\n\t\t'username' => '%s',\n\t\t'password' => '%s',\n\t\t'database' => '%s',\n\t\t'charset'  => 'utf8mb4',\n\t],\n\n" \
      "$(esc "$DB_HOST")" "$(esc "$DB_PORT")" "$(esc "$DB_USER")" "$(esc "$DB_PASSWORD")" "$(esc "$DB_NAME")"
    printf "\t'config' => [\n\t\t'admin_email'     => '%s',\n\t\t'sitename'        => '%s',\n" \
      "$(esc "$ADMIN_MAIL")" "$(esc "$ORG_NAME")"

    # Seeded on first boot only: afterwards the database (and therefore the officer
    # console) governs registration policy, and rewriting it here would silently
    # override an officer who opened or closed sign-ups.
    if [[ "$with_policy" == "yes" ]]; then
      printf "\t\t'register_policy' => \\Friendica\\Module\\Register::APPROVE,\n"
    fi

    # The pidfile is not optional: core's daemon refuses to start without it ("Please
    # set system.pidfile in config/local.config.php"), so the worker container exited
    # cleanly on every boot and was restarted for ever, doing no background work at all.
    # Each container has its own filesystem, so this path holds the worker's own pid.
    printf "\t],\n\n\t'system' => [\n\t\t'default_timezone' => 'UTC',\n\t\t'language'         => 'en',\n\t\t'url'              => '%s',\n\t\t'loglevel'         => 'NOTICE',\n\t\t'debugging'        => false,\n\t\t'pidfile'          => '/var/www/friendica/daemon.pid',\n\t],\n];\n" "$(esc "$BASE_URL")"
  } > "$CORE/config/local.config.php"

  # Friendica decides "installed" by the presence of exactly this path, so it must
  # exist (it is the file just written) - no separate marker step needed.
}

# Seeds the organization profile before anyone logs in. OrgConfig reads this file
# only when no stored value exists, so regenerating it never overrides the console.
write_orgsuite_defaults() {
  {
    printf '<?php\n\n/**\n * Generated by docker-entrypoint.sh from the container environment - do not edit.\n *\n * Read by OrgConfig as a fallback behind stored values: changing the profile or\n * features in the officer console wins over this file from then on.\n */\n\nreturn [\n'
    printf "\t'profile'  => '%s',\n" "$(esc "$ORG_PROFILE")"

    if [[ -n "$ORG_NAME" ]]; then
      printf "\t'org_name' => '%s',\n" "$(esc "$ORG_NAME")"
    fi

    printf '];\n'
  } > "$CORE/config/orgsuite.config.php"
}

first_boot() {
  log "first boot against '$DB_NAME': creating the schema"

  # `dbstructure update` is the schema creation the installer runs anyway, without
  # the environment checks that make `autoinstall` abort-while-exiting-0 (see
  # tools/dev/instance.sh for the full story).
  console dbstructure update >/dev/null 2>&1 \
    || die "'dbstructure update' failed; inspect with: docker compose logs app"

  local tables
  tables="$(sql "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='$DB_NAME';")"
  [[ "${tables:-0}" -gt 50 ]] || die "installation left only ${tables:-0} tables in '$DB_NAME'"
  log "schema installed ($tables tables)"

  log "creating administrator '$ADMIN_NICK'"
  printf '\n' | console user add "$ADMIN_NICK" "$ADMIN_NICK" "$ADMIN_MAIL" en 2>&1 | tail -2 || true

  local uid
  uid="$(sql "SELECT uid FROM user WHERE nickname='$ADMIN_NICK';" 2>/dev/null || true)"
  [[ -n "$uid" ]] || die "administrator '$ADMIN_NICK' was not created"

  # A CLI-created account has no usable password until one is set.
  console user password "$ADMIN_NICK" "$ADMIN_PASS" 2>&1 | tail -1 || true

  # A pending-approval admin could never open the console to approve anyone.
  sql "UPDATE user SET blocked=0, verified=1, account_removed=0 WHERE uid=$uid;" \
    || die "could not release the administrator account"

  log "enabling the orgsuite addon"
  console addon enable orgsuite >/dev/null 2>&1 \
    || die "'addon enable orgsuite' failed"

  console config config register_policy 1 >/dev/null 2>&1 || log "warning: could not set register_policy"

  log "activating the organization skin"
  console config system theme orgtool >/dev/null 2>&1 || true

  # Core's icon configuration is wired by the addon itself (Hooks::wireSiteIcons) rather
  # than here: it must only replace values that were never customised, which is a
  # decision that has to be made against live config, not at a fixed point in a script.

  log "ready at $BASE_URL (admin $ADMIN_NICK)"
}

provision() {
  log "waiting for the database at $DB_HOST:$DB_PORT"
  # Core's own readiness probe: host, port, timeout in seconds.
  ( cd "$CORE" && php bin/wait-for-connection "$DB_HOST" "$DB_PORT" 90 ) \
    || die "the database never became reachable"

  write_orgsuite_defaults

  if is_installed; then
    log "schema already present - keeping stored settings untouched"
    write_local_config no
    # Re-runs the migration path on every boot so an image upgrade that ships a
    # schema change applies itself instead of waiting for someone to run a command.
    console dbstructure update >/dev/null 2>&1 \
      || log "warning: 'dbstructure update' reported a problem; check the logs"
  else
    write_local_config yes
    first_boot
  fi

  # NOTE: nothing has to be done here to make new routes visible. Since 2026.10 the
  # addon compares its own route revision against the stored one on every request and
  # rebuilds Friendica's cached route table itself (see Hooks::invalidateRoutesAfterUpgrade).
  # An earlier version of this script tried `console cache set routerDispatchData 0`,
  # which always failed - core refuses to overwrite an array-typed key - and only looked
  # like it worked because the failure was guarded.
}

mode="${1:-app}"

# The image's CMD was the bare Apache command for a while, which the case below did
# not recognise: the container provisioned the database, then died, then restart-looped
# - and a fresh install ended with the installer timing out against a site that had no
# web server running at all. Normalising it here keeps an older image, or a container
# somebody runs by hand with that argument, working; the Dockerfile now says `app`.
case "$mode" in
  app|apache2-foreground) mode="app" ;;
  worker)                 ;;
  *) die "unknown mode '$mode' (want 'app' or 'worker')" ;;
esac

provision

case "$mode" in
  # `start -f` rather than the bare command: without --foreground the daemon forks and
  # the parent exits 0, which a container reads as "the process finished" and restarts
  # for ever - so the worker looked busy while doing nothing.
  worker) exec gosu www-data php bin/console.php daemon start -f ;;
  app)    exec apache2-foreground ;;
esac
