#!/usr/bin/env bash
#
# Provisions a complete Friendica instance headlessly, so a fresh machine or a CI runner can
# stand one up without clicking through the web installer.
#
#   tools/dev/instance.sh provision <config-dir> <db> <base-url> [sitename]
#   tools/dev/instance.sh destroy   <config-dir> <db>
#
# Why this exists: the end-to-end suite is only meaningful against an instance that was built
# the same way every time. Doing that by hand meant the suite could only ever be run on one
# developer's machine, with an instance nobody could reproduce — which is not a test, it is a
# memory. Everything below is a command a human would otherwise type.
#
# It never touches friendica/config/local.config.php. The instance's configuration lives in
# <config-dir>, selected with Friendica's own FRIENDICA_CONFIG_DIR mechanism, so several
# instances can share one checkout of the code without overwriting each other's settings.
#
# Environment (all optional, defaults suit the project-local database from tools/dev/devdb.sh):
#   DEV_DB_PORT, DEV_DB_USER, DEV_DB_PASS   database coordinates
#   ORGSUITE_ADMIN_NICK, ORGSUITE_ADMIN_PASS, ORGSUITE_ADMIN_MAIL
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CORE="$REPO_ROOT/friendica"
CONSOLE="$CORE/bin/console.php"

DB_PORT="${DEV_DB_PORT:-3316}"
DB_USER="${DEV_DB_USER:-friendica}"
DB_PASS="${DEV_DB_PASS:-friendica}"
SOCKET="$REPO_ROOT/.local/mariadb/run/mysqld.sock"

ADMIN_NICK="${ORGSUITE_ADMIN_NICK:-admin}"
ADMIN_PASS="${ORGSUITE_ADMIN_PASS:-DevAdmin!2026}"
ADMIN_MAIL="${ORGSUITE_ADMIN_MAIL:-admin@example.com}"

# Needed on hosts whose system openssl.cnf is missing, or Friendica cannot create keypairs.
export OPENSSL_CONF="${OPENSSL_CONF:-$REPO_ROOT/tools/dev/openssl.cnf}"

log()  { printf '\033[36m[instance]\033[0m %s\n' "$*"; }
ok()   { printf '\033[32m[instance]\033[0m %s\n' "$*"; }
die()  { printf '\033[31m[instance] %s\033[0m\n' "$*" >&2; exit 1; }

# Resolves a possibly-relative path against the current directory without requiring it to
# exist. The configuration directory is handed to php as FRIENDICA_CONFIG_DIR while the working
# directory is the core tree, so a relative path there silently points somewhere else and the
# install produces an empty database. Absolute paths are left alone.
abs() { case "$1" in /*) printf '%s' "$1" ;; *) printf '%s/%s' "$PWD" "$1" ;; esac; }

CONFIG_DIR=""
DB=""

# Runs bin/console with this instance's configuration directory selected.
console() {
  ( cd "$CORE" && FRIENDICA_CONFIG_DIR="$CONFIG_DIR" php "$CONSOLE" "$@" )
}

sql_root() {
  mariadb --socket="$SOCKET" -u root "$@"
}

# Is the application already installed against this database? The config table only exists
# after a successful installation, which makes it a reliable "have we done this already" test
# and lets `provision` be re-run without destroying an instance someone is using.
is_installed() {
  local count
  count="$(sql_root -N -B -e \
    "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='$DB' AND table_name='config';" 2>/dev/null || echo 0)"
  [[ "$count" == "1" ]]
}

# The install marker's first line, used to recognise a marker we created (and only that) when
# tearing an instance down.
INSTALL_MARKER_SIGNATURE='Install marker — generated by tools/dev/instance.sh'

# The configuration body, emitted once and used for both files so they cannot drift apart.
config_body() {
  local base_url="$1" sitename="$2"

  cat <<PHP
return [
	'database' => [
		'hostname' => '127.0.0.1:$DB_PORT',
		'username' => '$DB_USER',
		'password' => '$DB_PASS',
		'database' => '$DB',
		'charset'  => 'utf8mb4',
	],

	'config' => [
		// Whose account is a site administrator: Friendica grants that by matching the
		// logged-in user's email address against this value, there is no admin flag on the
		// user row. Get this wrong and the admin console silently refuses to open.
		'admin_email'     => '$ADMIN_MAIL',
		'sitename'        => '$sitename',
		'register_policy' => \Friendica\Module\Register::APPROVE,
	],

	'system' => [
		'default_timezone' => 'UTC',
		'language'         => 'en',
		'url'              => '$base_url',
		'loglevel'         => 'DEBUG',
		// Kept inside this instance's own directory. The previous hand-written config
		// hardcoded an absolute path, which silently broke the moment the tree moved.
		'logfile'          => '$CONFIG_DIR/friendica.log',
		'debugging'        => true,
	],
];
PHP
}

write_config() {
  local base_url="$1" sitename="$2"

  mkdir -p "$CONFIG_DIR"

  {
    printf '<?php\n\n/**\n * Generated by tools/dev/instance.sh — do not edit by hand.\n *\n * This file belongs to ONE provisioned instance. It is deliberately outside\n * friendica/config/ so that several instances can share a single checkout of the code:\n * select this directory with the FRIENDICA_CONFIG_DIR environment variable.\n *\n * The credentials below are the throw-away values of the project-local MariaDB that\n * tools/dev/devdb.sh starts on port %s. Never reuse them anywhere real.\n */\n\n' "$DB_PORT"
    config_body "$base_url" "$sitename"
  } > "$CONFIG_DIR/local.config.php"

  ensure_install_marker "$base_url" "$sitename"
}

# Makes sure Friendica agrees that this checkout is installed.
#
# src/App/Mode.php: determine() decides "installed" by looking for an EXACT path,
# $basePath/config/local.config.php, and it does NOT consult FRIENDICA_CONFIG_DIR when doing so.
# With no file there the application runs in install mode and every console command that touches
# user accounts refuses with "Database isn't ready or populated yet" - even though the schema
# exists and the database is fully configured. A rehearsal on a fresh checkout found exactly that;
# locally it never showed up, because the developer's own config file happened to satisfy the
# check. So this is not theoretical, and installing one must not depend on it.
#
# Two rules make it safe:
#   * an existing file is NEVER overwritten, so a developer's own configuration is untouched;
#   * the file written carries the instance's real values, so it cannot mislead if anything does
#     read it. It is at a path upstream's .gitignore excludes (/config/*.config.php), so creating
#     it does not affect the "core is untouched" guarantee.
ensure_install_marker() {
  local base_url="$1" sitename="$2"
  local marker="$CORE/config/local.config.php"

  if [[ -f "$marker" ]]; then
    log "install marker already present (left untouched)"
    return 0
  fi

  mkdir -p "$(dirname "$marker")"

  {
    printf '<?php\n\n/**\n * %s. Removed again by `instance.sh destroy`.\n *\n * Friendica decides whether it is installed by looking for this exact path and does not consult\n * FRIENDICA_CONFIG_DIR to do so; without it, console commands refuse to run. This file is a\n * marker, not the instance configuration, which lives in %s - the values below are repeated\n * so that this file is still correct if anything reads it.\n */\n\n' \
      "$INSTALL_MARKER_SIGNATURE" "$CONFIG_DIR"
    config_body "$base_url" "$sitename"
  } > "$marker"

  log "created the install marker ($marker)"
}

provision() {
  CONFIG_DIR="$(abs "$1")"; DB="$2"; local base_url="$3"; local sitename="${4:-Sunset Hills HOA}"

  [[ -n "$1" && -n "$DB" && -n "$base_url" ]] || die "usage: $0 provision <config-dir> <db> <base-url> [sitename]"
  [[ -d "$CORE" ]] || die "no Friendica checkout at $CORE"

  command -v mariadb >/dev/null || die "mariadb client not found"
  command -v php     >/dev/null || die "php not found"

  log "database: $DB on 127.0.0.1:$DB_PORT"

  # devdb.sh owns database and user creation; asking it to make ours keeps one copy of that
  # SQL, and re-running it against an existing database is a no-op.
  DEVDB_NAME="$DB" "$REPO_ROOT/tools/dev/devdb.sh" init >/dev/null || die "devdb.sh init failed"

  log "config: $CONFIG_DIR/local.config.php"
  write_config "$base_url" "$sitename"

  if is_installed; then
    log "schema already present in '$DB' — skipping installation"
  else
    log "creating the database schema"

    # Deliberately NOT 'autoinstall'. It runs environment checks that require the GMP PHP
    # module and aborts when it is missing — while still exiting 0. A script that trusts its
    # exit status therefore reports a successful install against a completely empty database,
    # and the failure surfaces much later as "table doesn't exist". dbstructure update is the
    # same schema creation without those checks, and is what the installer runs anyway.
    if ! console dbstructure update >/dev/null 2>&1; then
      die "'dbstructure update' failed; re-run it by hand to see the error:
    cd $CORE && FRIENDICA_CONFIG_DIR=$CONFIG_DIR php bin/console.php dbstructure update"
    fi

    # Judge the install by the artifact it produced, never by the exit status of the command
    # that claimed to produce it.
    local tables
    tables="$(sql_root -N -B -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='$DB';")"
    [[ "${tables:-0}" -gt 50 ]] || die "installation left only ${tables:-0} tables in '$DB'"
    ok "schema installed ($tables tables)"
  fi

  # autoinstall records config.admin_email but does NOT create an account, so the admin has
  # to be created separately or the console has nobody who can open it.
  local uid
  uid="$(sql_root -N -B -e "SELECT uid FROM \`$DB\`.user WHERE nickname='$ADMIN_NICK';" 2>/dev/null || true)"

  if [[ -z "$uid" ]]; then
    log "creating administrator '$ADMIN_NICK'"

    # 'user add' prompts for an avatar URL. With no stdin at all it fails with a generic
    # "An error occurred during registration" that says nothing about the prompt; an empty
    # line accepts it. Output is kept so a real failure is readable instead of guessed at.
    local add_output
    add_output="$(printf '\n' | console user add "$ADMIN_NICK" "$ADMIN_NICK" "$ADMIN_MAIL" en 2>&1)" || true

    uid="$(sql_root -N -B -e "SELECT uid FROM \`$DB\`.user WHERE nickname='$ADMIN_NICK';" 2>/dev/null || true)"

    if [[ -z "$uid" ]]; then
      printf '%s\n' "$add_output" >&2
      die "administrator '$ADMIN_NICK' was not created"
    fi
  else
    log "administrator '$ADMIN_NICK' already exists (uid $uid)"
  fi

  # A CLI-created account has no usable password until one is set, and the suite signs in.
  local pw_output
  pw_output="$(console user password "$ADMIN_NICK" "$ADMIN_PASS" 2>&1)" || true
  printf '%s' "$pw_output" | grep -qi 'changed' \
    || die "could not set a password for $ADMIN_NICK: $pw_output"

  # The account must be able to sign in immediately: this instance is a test fixture, and a
  # pending-approval admin would make every later check fail for an unrelated reason.
  sql_root -e "UPDATE \`$DB\`.user SET blocked=0, verified=1, account_removed=0 WHERE uid=$uid;" \
    || die "could not release the administrator account"

  log "enabling the orgsuite addon"
  console addon enable orgsuite >/dev/null 2>&1 \
    || die "'addon enable orgsuite' failed; is addon/orgsuite present in $CORE?"

  # Gated registration must be on for the suite's sign-up checks, and APPROVE makes Friendica
  # hold the account. Both are asserted here rather than assumed, because a silent miss turns
  # into a confusing failure much later in the run.
  console config config register_policy 1 >/dev/null 2>&1 || log "warning: could not set register_policy"

  local enabled additions
  enabled="$(console addon list enabled 2>/dev/null | grep -c 'orgsuite' || true)"
  [[ "$enabled" -ge 1 ]] || die "orgsuite does not report as enabled after enabling it"

  additions="$(sql_root -N -B -e \
    "SELECT COUNT(*) FROM \`$DB\`.config WHERE cat='addons' AND k='orgsuite';" 2>/dev/null || echo 0)"
  [[ "$additions" -ge 1 ]] || die "no orgsuite row was written to the config table"

  # Selecting the skin matters as much as shipping it. A theme that is present in the tree but
  # never enabled is untested code, and the site quietly keeps rendering its parent instead.
  log "activating the organization skin"
  console config system theme orgtool >/dev/null 2>&1 || true

  local active_theme
  active_theme="$(sql_root -N -B -e \
    "SELECT v FROM \`$DB\`.config WHERE cat='system' AND k='theme';" 2>/dev/null || true)"
  [[ "$active_theme" == *orgtool* ]] || die "the orgtool theme was not activated (system.theme=${active_theme:-unset})"
  ok "theme orgtool active"

  ok "$DB ready at $base_url (admin $ADMIN_NICK)"
}

destroy() {
  CONFIG_DIR="$(abs "$1")"; DB="$2"

  [[ -n "$1" && -n "$DB" ]] || die "usage: $0 destroy <config-dir> <db>"

  log "dropping database '$DB'"
  sql_root -e "DROP DATABASE IF EXISTS \`$DB\`;" || die "could not drop $DB"

  if [[ -d "$CONFIG_DIR" ]]; then
    log "removing $CONFIG_DIR"
    rm -rf "$CONFIG_DIR"
  fi

  # Remove the install marker, but ONLY if we wrote it. A developer's own config sits at the same
  # path, and deleting that because a throwaway instance was torn down would be a serious
  # accident.
  local marker="$CORE/config/local.config.php"
  if [[ -f "$marker" ]] && grep -qF "$INSTALL_MARKER_SIGNATURE" "$marker" 2>/dev/null; then
    log "removing our install marker"
    rm -f "$marker"
  fi

  ok "destroyed '$DB'"
}

case "${1:-}" in
  provision) shift; provision "$@" ;;
  destroy)   shift; destroy "$@" ;;
  *) die "usage: $0 {provision|destroy} ..." ;;
esac
